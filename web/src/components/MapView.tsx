import type { Feature, FeatureCollection } from "geojson";
import {
  AttributionControl,
  Map as MlMap,
  type ExpressionSpecification,
  type GeoJSONSource,
  type MapLayerMouseEvent,
  type MapMouseEvent,
  Popup,
  type ResourceType,
  setWorkerUrl,
  type StyleSpecification,
} from "maplibre-gl";
import "maplibre-gl/dist/maplibre-gl.css";
// MapLibre builds its worker path from a variable, which the bundler cannot see,
// so the worker file was never emitted and production fell through to index.html.
// Importing it with ?url makes Vite ship it as a hashed asset we can point at.
import workerUrl from "maplibre-gl/dist/maplibre-gl-worker.mjs?url";

setWorkerUrl(workerUrl);
import { useEffect, useRef } from "react";
import type { LatLng } from "../lib/hooks";
import type { State } from "../lib/status";

export type MapPoint = {
  id: string;
  name: string;
  /** One-line status, shown in the hover tooltip. */
  subtitle: string;
  lat: number;
  lng: number;
  state: State;
  favourite: boolean;
};

type Props = {
  points: MapPoint[];
  selectedId: string | null;
  onSelect: (id: string | null) => void;
  me: LatLng | null;
  dark: boolean;
  /** Screen space covered by floating UI, so fly-to centres in the visible part. */
  padding: { top: number; bottom: number; left: number; right: number };
  /** Bumped to fly the camera to the selection (list taps), but not for map taps. */
  focusKey: number;
  /** Bumped to fly to the user's location. */
  meKey: number;
};

// Free, keyless vector tiles (OpenMapTiles schema). Swap for self-hosted
// PMTiles (as TransitGo does) if traffic ever warrants it.
const STYLE_URL = {
  light: "https://tiles.openfreemap.org/styles/positron",
  dark: "https://tiles.openfreemap.org/styles/dark",
};

const SG_CENTER: [number, number] = [103.8198, 1.3521];
const SG_BOUNDS: [number, number, number, number] = [103.45, 1.1, 104.2, 1.55];

/**
 * Map labels in Inter, matching the UI.
 *
 * MapLibre draws text from pre-rendered SDF glyph files, so CSS
 * `font-feature-settings` never reaches it. public/fonts/glyphs is generated by
 * scripts/build-glyphs.py from InterVariable with cv05 and cv11 baked in, so map
 * labels get the same alternates as the rest of the app. Only Latin ranges are
 * shipped; anything else falls back to OpenFreeMap's Noto glyphs.
 */
const GLYPHS_URL = `${window.location.origin}/fonts/glyphs/{fontstack}/{range}.pbf`;
const OWN_RANGES = new Set(["0-255", "256-511", "8192-8447"]);
const NOTO_TO_INTER: Record<string, string> = {
  "Noto Sans Regular": "Inter Regular",
  "Noto Sans Italic": "Inter Regular",
  "Noto Sans Bold": "Inter Bold",
};
const INTER_TO_NOTO: Record<string, string> = { "Inter Regular": "Noto Sans Regular", "Inter Medium": "Noto Sans Regular", "Inter Bold": "Noto Sans Bold" };

function interize(value: unknown): unknown {
  if (typeof value === "string") return NOTO_TO_INTER[value] ?? value;
  if (Array.isArray(value)) return value.map(interize);
  return value;
}

/** Point the basemap's labels at our Inter glyphs. */
function transformStyle(_previous: StyleSpecification | undefined, next: StyleSpecification): StyleSpecification {
  return {
    ...next,
    glyphs: GLYPHS_URL,
    layers: next.layers.map((layer) =>
      layer.type === "symbol" && layer.layout?.["text-font"]
        ? { ...layer, layout: { ...layer.layout, "text-font": interize(layer.layout["text-font"]) as string[] } }
        : layer,
    ),
  };
}

/** Glyph ranges we do not ship (e.g. Tamil, CJK punctuation) come from OpenFreeMap's Noto set. */
function transformRequest(url: string, type?: ResourceType) {
  if (type === "Glyphs") {
    const match = /\/fonts\/glyphs\/([^/]+)\/(\d+-\d+)\.pbf$/.exec(url);
    if (match && !OWN_RANGES.has(match[2])) {
      const stack = INTER_TO_NOTO[decodeURIComponent(match[1])] ?? "Noto Sans Regular";
      return { url: `https://tiles.openfreemap.org/fonts/${encodeURIComponent(stack)}/${match[2]}.pbf` };
    }
  }
  return { url };
}

const fallbackStyle = (dark: boolean): StyleSpecification => ({
  version: 8,
  glyphs: GLYPHS_URL,
  sources: {},
  layers: [{ id: "background", type: "background", paint: { "background-color": dark ? "#0c0c0c" : "#f2f3f0" } }],
});

function token(name: string): string {
  return getComputedStyle(document.documentElement).getPropertyValue(name).trim() || "#888";
}

function toGeoJSON(points: MapPoint[]): FeatureCollection {
  return {
    type: "FeatureCollection",
    features: points.map((p) => ({
      type: "Feature",
      id: p.id,
      geometry: { type: "Point", coordinates: [p.lng, p.lat] },
      properties: { id: p.id, name: p.name, subtitle: p.subtitle, state: p.state, fav: p.favourite ? 1 : 0 },
    })),
  };
}

function addLayers(map: MlMap, points: MapPoint[], me: LatLng | null) {
  const colour = (s: State) => token(`--status-${s}`);
  const surface = token("--surface");
  const text = token("--text-primary");

  map.addSource("hawkers", { type: "geojson", data: toGeoJSON(points), promoteId: "id" });
  map.addSource("me", {
    type: "geojson",
    data: { type: "FeatureCollection", features: me ? [pointFeature(me)] : [] },
  });

  const radius = (extra: number): ExpressionSpecification => [
    "interpolate",
    ["linear"],
    ["zoom"],
    10,
    ["+", ["match", ["get", "state"], ["closed", "works"], 5.5, 4.5], extra],
    14,
    ["+", ["match", ["get", "state"], ["closed", "works"], 10, 8], extra],
  ];

  map.addLayer({
    id: "hawkers-halo",
    type: "circle",
    source: "hawkers",
    filter: ["==", ["get", "id"], ""],
    paint: {
      "circle-radius": radius(8),
      "circle-color": text,
      "circle-opacity": 0.14,
      "circle-stroke-width": 2,
      "circle-stroke-color": text,
    },
  });

  map.addLayer({
    id: "hawkers",
    type: "circle",
    source: "hawkers",
    layout: {
      // Closed on top: the thing you are scanning for should never be hidden under an open pin.
      "circle-sort-key": ["match", ["get", "state"], "closed", 4, "works", 3, "soon", 2, 1],
    },
    paint: {
      "circle-radius": radius(0),
      "circle-color": [
        "match",
        ["get", "state"],
        "closed",
        colour("closed"),
        "works",
        colour("works"),
        "soon",
        colour("soon"),
        colour("open"),
      ],
      // Closed pins get a dark ring as a second, non-colour cue.
      "circle-stroke-width": ["match", ["get", "state"], ["closed", "works"], 3, 2],
      "circle-stroke-color": ["match", ["get", "state"], ["closed", "works"], text, surface],
      "circle-opacity": ["case", ["boolean", ["feature-state", "dim"], false], 0.35, 1],
    },
  });

  map.addLayer({
    id: "hawkers-label",
    type: "symbol",
    source: "hawkers",
    minzoom: 13,
    layout: {
      "text-field": ["concat", ["case", ["==", ["get", "fav"], 1], "★ ", ""], ["get", "name"]],
      "text-font": ["Inter Medium"],
      "text-size": 12,
      "text-offset": [0, 1.3],
      "text-anchor": "top",
      "text-max-width": 9,
      "text-optional": true,
      "symbol-sort-key": ["match", ["get", "state"], "closed", 0, "works", 1, "soon", 2, 3],
    },
    paint: {
      "text-color": text,
      "text-halo-color": surface,
      "text-halo-width": 1.6,
    },
  });

  map.addLayer({
    id: "me-pulse",
    type: "circle",
    source: "me",
    paint: { "circle-radius": 16, "circle-color": token("--me"), "circle-opacity": 0.18 },
  });
  map.addLayer({
    id: "me",
    type: "circle",
    source: "me",
    paint: {
      "circle-radius": 6.5,
      "circle-color": token("--me"),
      "circle-stroke-width": 2.5,
      "circle-stroke-color": "#ffffff",
    },
  });
}

function pointFeature(p: LatLng): Feature {
  return { type: "Feature", geometry: { type: "Point", coordinates: [p.lng, p.lat] }, properties: {} };
}

export function MapView({ points, selectedId, onSelect, me, dark, padding, focusKey, meKey }: Props) {
  const container = useRef<HTMLDivElement>(null);
  const mapRef = useRef<MlMap | null>(null);
  const ready = useRef(false);
  const latest = useRef({ points, me, selectedId, onSelect });
  latest.current = { points, me, selectedId, onSelect };

  // Create once.
  useEffect(() => {
    if (!container.current) return;
    const map = new MlMap({
      container: container.current,
      // A flat background first; the real basemap loads straight after, through
      // transformStyle. If the tile host is down, the pins still draw on this.
      style: fallbackStyle(dark),
      transformRequest,
      center: SG_CENTER,
      zoom: window.innerWidth < 640 ? 10.2 : 10.9,
      minZoom: 9.5,
      maxZoom: 18,
      maxBounds: SG_BOUNDS,
      attributionControl: false,
      dragRotate: false,
      pitchWithRotate: false,
      touchPitch: false,
    });
    map.touchZoomRotate.disableRotation();
    // Bottom-right on desktop; on phones the bottom belongs to the card, so tuck it
    // under the top bar instead (offset in styles.css).
    map.addControl(new AttributionControl({ compact: true }), window.innerWidth < 900 ? "top-left" : "bottom-right");
    mapRef.current = map;
    if (import.meta.env.DEV) (window as unknown as { __map: MlMap }).__map = map;

    const onStyle = () => {
      const { points, me, selectedId } = latest.current;
      if (!map.getSource("hawkers")) addLayers(map, points, me);
      map.setFilter("hawkers-halo", ["==", ["get", "id"], selectedId ?? ""]);
      ready.current = true;
    };
    map.on("style.load", onStyle);
    map.setStyle(dark ? STYLE_URL.dark : STYLE_URL.light, { diff: false, transformStyle });
    map.on("error", (e) => console.warn("map:", e.error?.message ?? e));

    map.on("click", "hawkers", (e: MapLayerMouseEvent) => {
      const id = e.features?.[0]?.properties?.id as string | undefined;
      if (id) latest.current.onSelect(id);
    });
    map.on("click", (e: MapMouseEvent) => {
      const hit = map.queryRenderedFeatures(e.point, { layers: ["hawkers"] });
      if (!hit.length) latest.current.onSelect(null);
    });
    // Hover tooltip, for real pointers only (a tap already opens the card).
    const tooltip = new Popup({
      closeButton: false,
      closeOnClick: false,
      offset: 14,
      maxWidth: "260px",
      className: "hgw-tooltip",
    });
    const canHover = window.matchMedia("(hover: hover) and (pointer: fine)").matches;
    let hovered: string | null = null;
    map.on("mousemove", "hawkers", (e: MapLayerMouseEvent) => {
      map.getCanvas().style.cursor = "pointer";
      const feature = e.features?.[0];
      if (!canHover || !feature || feature.geometry.type !== "Point") return;
      const { id, name, subtitle } = feature.properties as { id: string; name: string; subtitle: string };
      if (hovered === id) return;
      hovered = id;
      const body = document.createElement("div");
      const title = document.createElement("strong");
      title.textContent = name;
      const line = document.createElement("span");
      line.textContent = subtitle;
      body.append(title, line);
      tooltip
        .setLngLat(feature.geometry.coordinates as [number, number])
        .setDOMContent(body)
        .addTo(map);
    });
    map.on("mouseleave", "hawkers", () => {
      map.getCanvas().style.cursor = "";
      hovered = null;
      tooltip.remove();
    });

    return () => {
      tooltip.remove();
      ready.current = false;
      map.remove();
      mapRef.current = null;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  // Theme switch: swap basemap, then re-add our layers with the new tokens.
  const firstScheme = useRef(true);
  useEffect(() => {
    if (firstScheme.current) {
      firstScheme.current = false;
      return;
    }
    const map = mapRef.current;
    if (!map) return;
    ready.current = false;
    map.setStyle(dark ? STYLE_URL.dark : STYLE_URL.light, { diff: false, transformStyle });
  }, [dark]);

  useEffect(() => {
    const source = mapRef.current?.getSource("hawkers") as GeoJSONSource | undefined;
    source?.setData(toGeoJSON(points));
  }, [points]);

  useEffect(() => {
    const source = mapRef.current?.getSource("me") as GeoJSONSource | undefined;
    source?.setData({ type: "FeatureCollection", features: me ? [pointFeature(me)] : [] });
  }, [me]);

  useEffect(() => {
    const map = mapRef.current;
    if (map && ready.current) map.setFilter("hawkers-halo", ["==", ["get", "id"], selectedId ?? ""]);
  }, [selectedId]);

  useEffect(() => {
    mapRef.current?.setPadding(padding);
  }, [padding]);

  useEffect(() => {
    if (!focusKey) return;
    const map = mapRef.current;
    const target = points.find((p) => p.id === selectedId);
    if (!map || !target) return;
    map.easeTo({ center: [target.lng, target.lat], zoom: Math.max(map.getZoom(), 14.5), padding, duration: 700 });
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [focusKey]);

  useEffect(() => {
    if (!meKey || !me) return;
    mapRef.current?.easeTo({ center: [me.lng, me.lat], zoom: 14, padding, duration: 700 });
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [meKey, me]);

  // Wrapped: maplibre-gl.css sets `.maplibregl-map { position: relative }` unlayered,
  // which outranks Tailwind's layered `absolute` on the same element.
  return (
    <div className="absolute inset-0">
      <div ref={container} className="h-full w-full" aria-label="Map of hawker centres" />
    </div>
  );
}
